// Package config loads and validates the chatbridge configuration.
//
// Defaults are seeded before decoding, so any field absent from the YAML
// keeps its default while present fields override it. Validate() then rejects
// configs that cannot run. See §2 of the plan — this shape is fixed.
package config

import (
	"fmt"
	"os"

	"gopkg.in/yaml.v3"
)

// Config is the whole configuration file.
type Config struct {
	Server  Server   `yaml:"server"`
	Twitch  Twitch   `yaml:"twitch"`
	Limits  Limits   `yaml:"limits"`
	Mode    Mode     `yaml:"mode"`
	Actions []Action `yaml:"actions"`
}

// Server holds the HTTP listener settings.
type Server struct {
	Addr       string `yaml:"addr"`
	AdminToken string `yaml:"admin_token"`
}

// Twitch holds the channel to read. Anonymous IRC — no token (see non-goals).
type Twitch struct {
	Channel string `yaml:"channel"`
}

// Limits are the safety valves. Zero is never a valid value here.
type Limits struct {
	UserCooldownSec     int `yaml:"user_cooldown_sec"`
	GlobalActionsPerMin int `yaml:"global_actions_per_min"`
	MaxLiveEntities     int `yaml:"max_live_entities"`
	QueueSize           int `yaml:"queue_size"`
}

// Mode configures automatic switching between individual and vote modes.
type Mode struct {
	AutoSwitch              bool `yaml:"auto_switch"`
	VoteThresholdMsgsPerMin int  `yaml:"vote_threshold_msgs_per_min"`
	VoteDurationSec         int  `yaml:"vote_duration_sec"`
}

// Action is one entry in the catalog. It is pure data — adding an action must
// never require a Go code change (see §2).
type Action struct {
	Name    string         `yaml:"name"`
	Aliases []string       `yaml:"aliases"`
	Type    string         `yaml:"type"`
	Params  map[string]any `yaml:"params"`
	TTL     int            `yaml:"ttl"`
	Weight  int            `yaml:"weight"`
}

// actionTypes are the event types a catalog action may declare. vote_* and
// system events are generated by the bridge, never authored in the catalog.
var actionTypes = map[string]bool{"spawn": true, "weather": true, "effect": true}

// defaults returns a Config pre-filled with the plan's default values.
func defaults() Config {
	return Config{
		Server: Server{Addr: ":8093"},
		Limits: Limits{
			UserCooldownSec:     30,
			GlobalActionsPerMin: 20,
			MaxLiveEntities:     40,
			QueueSize:           500,
		},
		Mode: Mode{
			AutoSwitch:              true,
			VoteThresholdMsgsPerMin: 60,
			VoteDurationSec:         20,
		},
	}
}

// Load reads and parses a config file from disk.
func Load(path string) (Config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return Config{}, fmt.Errorf("read config %q: %w", path, err)
	}
	return Parse(data)
}

// Parse decodes YAML over the defaults and validates the result. It is the
// seam the tests use — no disk, no network, no clock.
func Parse(data []byte) (Config, error) {
	cfg := defaults()
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return Config{}, fmt.Errorf("parse config: %w", err)
	}
	if err := cfg.Validate(); err != nil {
		return Config{}, fmt.Errorf("invalid config: %w", err)
	}
	return cfg, nil
}

// Validate rejects any config that cannot safely run.
func (c Config) Validate() error {
	if c.Server.Addr == "" {
		return fmt.Errorf("server.addr must not be empty")
	}
	if c.Server.AdminToken == "" {
		return fmt.Errorf("server.admin_token must be set (protects /admin/*)")
	}
	if c.Twitch.Channel == "" {
		return fmt.Errorf("twitch.channel is required")
	}
	if c.Limits.QueueSize <= 0 {
		return fmt.Errorf("limits.queue_size must be > 0")
	}
	if c.Limits.MaxLiveEntities <= 0 {
		return fmt.Errorf("limits.max_live_entities must be > 0")
	}
	if c.Limits.GlobalActionsPerMin <= 0 {
		return fmt.Errorf("limits.global_actions_per_min must be > 0")
	}
	if c.Mode.VoteDurationSec <= 0 {
		return fmt.Errorf("mode.vote_duration_sec must be > 0")
	}
	if c.Mode.VoteThresholdMsgsPerMin <= 0 {
		return fmt.Errorf("mode.vote_threshold_msgs_per_min must be > 0")
	}

	seen := make(map[string]bool, len(c.Actions))
	aliasSeen := make(map[string]string, len(c.Actions))
	for i, a := range c.Actions {
		if a.Name == "" {
			return fmt.Errorf("actions[%d]: name is required", i)
		}
		if seen[a.Name] {
			return fmt.Errorf("actions[%d]: duplicate action name %q", i, a.Name)
		}
		seen[a.Name] = true
		if !actionTypes[a.Type] {
			return fmt.Errorf("action %q: invalid type %q (want spawn|weather|effect)", a.Name, a.Type)
		}
		if len(a.Aliases) == 0 {
			return fmt.Errorf("action %q: at least one alias is required", a.Name)
		}
		for _, al := range a.Aliases {
			if prev, ok := aliasSeen[al]; ok {
				return fmt.Errorf("action %q: alias %q already used by %q", a.Name, al, prev)
			}
			aliasSeen[al] = a.Name
		}
		if a.Weight < 0 {
			return fmt.Errorf("action %q: weight must be >= 0", a.Name)
		}
	}
	return nil
}
